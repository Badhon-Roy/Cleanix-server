const getAllBlogsFromDB = async (): Promise<IBlog[]> => {
  const count = await Blog.countDocuments();
  if (count === 0) {
    await Blog.insertMany(defaultBlogsList);
  }
  return await Blog.find().sort({ createdAt: -1 });
};

const getBlogBySlugFromDB = async (slug: string): Promise<IBlog | null> => {
  let blog = await Blog.findOne({ slug });
  if (!blog) {
    // Check if auto-seed is needed
    const count = await Blog.countDocuments();
    if (count === 0) {
      await Blog.insertMany(defaultBlogsList);
      blog = await Blog.findOne({ slug });
    }
  }
  return blog;
};

const createBlogInDB = async (payload: IBlog): Promise<IBlog> => {
  const result = await Blog.create(payload);
  return result;
};

const updateBlogInDB = async (slug: string, payload: Partial<IBlog>): Promise<IBlog | null> => {
  const result = await Blog.findOneAndUpdate(
    { slug },
    { $set: payload },
    { new: true, upsert: true },
  );
  return result;
};

const deleteBlogFromDB = async (slug: string): Promise<IBlog | null> => {
  const result = await Blog.findOneAndDelete({ slug });
  return result;
};

export const BlogService = {
  getAllBlogsFromDB,
  getBlogBySlugFromDB,
  createBlogInDB,
  updateBlogInDB,
  deleteBlogFromDB,
};
